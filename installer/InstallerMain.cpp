/*  LOST DUCK Anti Feedback -- installer.

    Wears the plug-in's own face: the same casing artwork, the same screen, and the same
    orange button, which here is the accept control for the licence agreement.

    The plug-in itself travels inside this executable as a Win32 RCDATA resource rather
    than as a loose file beside it, so the download is one file and there is nothing for
    a user to lose track of. See installer/payload.rc, generated by CMake.

    Requires elevation -- the VST3 folder lives under Program Files. That is declared in
    the manifest via /MANIFESTUAC in CMakeLists.txt, so Windows asks before the process
    starts rather than failing halfway through a copy.
*/

