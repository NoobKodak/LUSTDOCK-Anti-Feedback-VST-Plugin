//==============================================================================
juce::MemoryBlock loadPayload (int resourceId)
{
    auto* const module = GetModuleHandleW (nullptr);
    // RT_RCDATA expands to the ANSI MAKEINTRESOURCE, which will not bind to the wide
    // FindResourceW. The numeric id behind it is the same either way.
    const auto* const rcDataType = MAKEINTRESOURCEW (10);

    auto* const found = FindResourceW (module, MAKEINTRESOURCEW (resourceId), rcDataType);

    if (found == nullptr)
        return {};

    auto* const handle = LoadResource (module, found);

    if (handle == nullptr)
        return {};

    const auto size = SizeofResource (module, found);
    const auto* const data = LockResource (handle);

    if (data == nullptr || size == 0)
        return {};

    return juce::MemoryBlock (data, size);
}

juce::String loadPayloadText (int resourceId)
{
    const auto block = loadPayload (resourceId);
    return juce::String::fromUTF8 (static_cast<const char*> (block.getData()),
                                   static_cast<int> (block.getSize()));
}

/** Serves the installer's own web assets, which are a separate bundle from the
    plug-in's -- same idea as source/WebResourceProvider.cpp. */
std::optional<juce::WebBrowserComponent::Resource> getInstallerResource (const juce::String& url)
{
    auto filename = url.upToFirstOccurrenceOf ("?", false, false)
                       .upToFirstOccurrenceOf ("#", false, false);

    if (filename.startsWith ("/"))
        filename = filename.substring (1);

    if (filename.isEmpty())
        filename = "index.html";

    filename = juce::URL::removeEscapeChars (filename).fromLastOccurrenceOf ("/", false, false);

    for (int i = 0; i < InstallerUiData::namedResourceListSize; ++i)
    {
        if (filename != InstallerUiData::originalFilenames[i])
            continue;

        int size = 0;
        const auto* const data = InstallerUiData::getNamedResource (InstallerUiData::namedResourceList[i], size);

        if (data == nullptr)
            break;

        const auto mime = filename.endsWithIgnoreCase (".html") ? "text/html;charset=UTF-8"
                        : filename.endsWithIgnoreCase (".js")   ? "text/javascript;charset=UTF-8"
                        : filename.endsWithIgnoreCase (".css")  ? "text/css;charset=UTF-8"
                        : filename.endsWithIgnoreCase (".svg")  ? "image/svg+xml"
                        : filename.endsWithIgnoreCase (".png")  ? "image/png"
                                                                : "application/octet-stream";

        const auto* const bytes = reinterpret_cast<const std::byte*> (data);
        return juce::WebBrowserComponent::Resource { std::vector<std::byte> (bytes, bytes + size),
                                                     juce::String (mime) };
    }

    return std::nullopt;
}

juce::var makeObject (std::initializer_list<std::pair<juce::Identifier, juce::var>> fields)
{
    auto* object = new juce::DynamicObject();

    for (const auto& field : fields)
        object->setProperty (field.first, field.second);

    return juce::var (object);
}

//==============================================================================
juce::File vst3Folder()
{
    // Asked for rather than hard-coded: on a machine where Windows lives somewhere other
    // than C:, "C:\Program Files" is simply wrong.
    const auto common = juce::SystemStats::getEnvironmentVariable ("CommonProgramFiles",
                                                                   "C:\\Program Files\\Common Files");
    return juce::File (common).getChildFile ("VST3");
}

juce::File docsFolder()
{
    const auto programs = juce::SystemStats::getEnvironmentVariable ("ProgramFiles",
                                                                     "C:\\Program Files");
    return juce::File (programs).getChildFile ("LOST").getChildFile (productName);
}

bool writeFile (const juce::File& destination, const juce::MemoryBlock& contents, juce::String& error)
{
    destination.getParentDirectory().createDirectory();

    juce::TemporaryFile temp (destination);

    if (auto stream = std::unique_ptr<juce::FileOutputStream> (temp.getFile().createOutputStream()))
    {
        if (stream->write (contents.getData(), contents.getSize()))
        {
            stream.reset();

            if (temp.overwriteTargetFileWithTemporary())
                return true;
        }
    }

    error = "Could not write " + destination.getFullPathName();
    return false;
}

/** Undoes what earlier builds did to the bundle: drops any desktop.ini inside it and
    clears the System attribute, so upgrading over one of those installs does not carry
    the problem forward. */
void clearSystemMarking (const juce::File& bundle)
{
    const auto ini = bundle.getChildFile ("desktop.ini");

    if (ini.existsAsFile())
    {
        SetFileAttributesW (ini.getFullPathName().toWideCharPointer(), FILE_ATTRIBUTE_NORMAL);
        ini.deleteFile();
    }

    const auto path = bundle.getFullPathName().toWideCharPointer();
    const auto attributes = GetFileAttributesW (path);

    if (attributes != INVALID_FILE_ATTRIBUTES && (attributes & FILE_ATTRIBUTE_SYSTEM) != 0)
        SetFileAttributesW (path, attributes & ~static_cast<DWORD> (FILE_ATTRIBUTE_SYSTEM));
}

/** A Windows .lnk. There is no portable way to do this -- it is COM or nothing. */
bool createShortcut (const juce::File& target, const juce::File& linkFile,
                     const juce::String& description)
{
    linkFile.getParentDirectory().createDirectory();

    IShellLinkW* link = nullptr;

    if (FAILED (CoCreateInstance (CLSID_ShellLink, nullptr, CLSCTX_INPROC_SERVER,
                                  IID_IShellLinkW, (void**) &link)))
        return false;

    bool ok = false;
    link->SetPath (target.getFullPathName().toWideCharPointer());
    link->SetWorkingDirectory (target.getParentDirectory().getFullPathName().toWideCharPointer());
    link->SetDescription (description.toWideCharPointer());
    link->SetIconLocation (target.getFullPathName().toWideCharPointer(), 0);

    IPersistFile* file = nullptr;

    if (SUCCEEDED (link->QueryInterface (IID_IPersistFile, (void**) &file)))
    {
        ok = SUCCEEDED (file->Save (linkFile.getFullPathName().toWideCharPointer(), TRUE));
        file->Release();
    }

    link->Release();
    return ok;
}

/** The Add or remove programs entry. Without this the plug-in is something a user can
    install and then never get rid of, which is not acceptable in a paid product. */
void registerWithWindows (const juce::File& uninstaller, const juce::File& iconFile,
                          juce::int64 sizeBytes)
{
    HKEY key = nullptr;

    if (RegCreateKeyExW (HKEY_LOCAL_MACHINE,
                         L"Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\LOSTDuckAntiFeedback",
                         0, nullptr, 0, KEY_WRITE, nullptr, &key, nullptr) != ERROR_SUCCESS)
        return;

    const auto setString = [key] (const wchar_t* name, const juce::String& value)
    {
        const auto* text = value.toWideCharPointer();
        RegSetValueExW (key, name, 0, REG_SZ, (const BYTE*) text,
                        (DWORD) ((wcslen (text) + 1) * sizeof (wchar_t)));
    };

    const auto setDword = [key] (const wchar_t* name, DWORD value)
    {
        RegSetValueExW (key, name, 0, REG_DWORD, (const BYTE*) &value, sizeof (value));
    };

    setString (L"DisplayName", productName);
    setString (L"DisplayVersion", "1.0.0");
    setString (L"Publisher", "LOST");
    setString (L"DisplayIcon", iconFile.getFullPathName());
    setString (L"InstallLocation", uninstaller.getParentDirectory().getFullPathName());
    setString (L"UninstallString", "\"" + uninstaller.getFullPathName() + "\" --uninstall");
    setString (L"QuietUninstallString", "\"" + uninstaller.getFullPathName() + "\" --uninstall --silent");
    setDword (L"NoModify", 1);
    setDword (L"NoRepair", 1);
    setDword (L"EstimatedSize", (DWORD) juce::jmax<juce::int64> (1, sizeBytes / 1024));

    RegCloseKey (key);
}

void unregisterFromWindows()
{
    RegDeleteKeyExW (HKEY_LOCAL_MACHINE,
                     L"Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\LOSTDuckAntiFeedback",
                     KEY_WOW64_64KEY, 0);
}

/** JUCE has no special-location id for the all-users Start menu or desktop, so these
    come from the shell directly. */
juce::File shellFolder (int csidl)
{
    wchar_t path[MAX_PATH] = {};

    if (SUCCEEDED (SHGetFolderPathW (nullptr, csidl, nullptr, SHGFP_TYPE_CURRENT, path)))
        return juce::File (juce::String (path));

    return {};
}

juce::File startMenuFolder()
{
    return shellFolder (0x0017).getChildFile ("LOST");   // CSIDL_COMMON_PROGRAMS
}

juce::File sharedDesktopFolder()
{
    return shellFolder (0x0019);                          // CSIDL_COMMON_DESKTOPDIRECTORY
}

/** Does the actual work. Returns an object the web page can read directly.

    `options` comes from the checkboxes on screen: which components, where the VST3 goes,
    and whether shortcuts are wanted. Everything is optional except the VST3 itself --
    a host that scans a custom folder is common enough that hard-coding the path would
    make this installer useless to a chunk of users. */
juce::var performInstall (const juce::var& options)
{
    const auto wantVst3 = ! options.hasProperty ("vst3") || (bool) options["vst3"];
    const auto wantStandalone = (bool) options["standalone"];
    const auto wantShortcuts = (bool) options["shortcuts"];
    const auto wantDesktop = (bool) options["desktop"];

    const juce::String customFolder = options["vst3Folder"].toString().trim();
    const auto targetVst3 = customFolder.isNotEmpty() ? juce::File (customFolder) : vst3Folder();

    juce::StringArray installed;
    juce::int64 totalBytes = 0;
    juce::String error;

    //---------------------------------------------------------------- VST3
    juce::File bundle;

    if (wantVst3)
    {
        const auto plugin = loadPayload (IDR_VST3_PAYLOAD);

        if (plugin.getSize() < 1024)
            return makeObject ({ { "ok", false },
                                 { "why", "This installer is damaged: the plug-in payload is missing. "
                                          "Please download it again." } });

        if (! targetVst3.createDirectory())
            return makeObject ({ { "ok", false },
                                 { "why", "Could not open " + targetVst3.getFullPathName()
                                          + ". Check the folder, or run the installer as administrator." } });

        bundle = targetVst3.getChildFile (juce::String (productName) + ".vst3");

        // Replaced wholesale rather than written over: leftover files from an older
        // bundle layout are exactly what makes a host scan fail undiagnosably.
        if (bundle.exists())
            bundle.deleteRecursively();

        const auto binary = bundle.getChildFile ("Contents").getChildFile ("x86_64-win")
                                  .getChildFile (juce::String (productName) + ".vst3");

        if (! writeFile (binary, plugin, error))
            return makeObject ({ { "ok", false },
                                 { "why", error + ". Try running the installer as administrator." } });

        totalBytes += (juce::int64) plugin.getSize();
        installed.add ("VST3 plug-in \u2014 " + bundle.getFullPathName());

        // Nothing else goes inside the bundle, and it is left with plain attributes.
        //
        // Earlier builds wrote a desktop.ini here and marked the folder +s so Explorer
        // would draw the duck on it. That made this the only bundle in the VST3
        // directory carrying the System attribute, and FL Studio would not verify it.
        // A folder icon is not worth being the odd one out in a plug-in scanner.
        clearSystemMarking (bundle);

        for (const auto* old : supersededBundles)
        {
            const auto stale = targetVst3.getChildFile (old);

            if (stale.exists())
                stale.deleteRecursively();
        }
    }

    //---------------------------------------------------------- standalone
    juce::File standaloneExe;

    if (wantStandalone)
    {
        const auto app = loadPayload (IDR_STANDALONE_PAYLOAD);

        if (app.getSize() > 1024)
        {
            standaloneExe = docsFolder().getChildFile (juce::String (productName) + ".exe");

            if (writeFile (standaloneExe, app, error))
            {
                totalBytes += (juce::int64) app.getSize();
                installed.add ("Standalone app \u2014 " + standaloneExe.getFullPathName());
            }
            else
            {
                standaloneExe = {};
            }
        }
    }

    //------------------------------------------------------------ the docs
    // The manual and licence travel with the binary.
    const auto iconFile = docsFolder().getChildFile ("icon-lostduck-multi.ico");

    {
        const auto icon = loadPayload (IDR_ICON_PAYLOAD);
        juce::String ignored;

        if (icon.getSize() > 0)
            writeFile (iconFile, icon, ignored);
    }

    for (const auto& doc : { std::pair<int, const char*> { IDR_MANUAL_TEXT, "MANUAL.md" },
                             std::pair<int, const char*> { IDR_THIRDPARTY_TEXT, "THIRD-PARTY.txt" },
                             std::pair<int, const char*> { IDR_EULA_TEXT, "LICENCE.txt" } })
    {
        const auto contents = loadPayload (doc.first);

        if (contents.getSize() > 0)
        {
            juce::String ignored;
            writeFile (docsFolder().getChildFile (doc.second), contents, ignored);
            totalBytes += (juce::int64) contents.getSize();
        }
    }

    //--------------------------------------------------------- uninstaller
    // A copy of this executable, kept so Windows has something to run later. It carries
    // the payload with it, which is wasteful in disk terms and much simpler than
    // shipping a second binary that has to be kept in step with this one.
    const auto uninstaller = docsFolder().getChildFile ("Uninstall " + juce::String (productName) + ".exe");
    juce::File::getSpecialLocation (juce::File::currentExecutableFile).copyFileTo (uninstaller);

    //----------------------------------------------------------- shortcuts
    if (wantShortcuts && standaloneExe.existsAsFile())
    {
        createShortcut (standaloneExe, startMenuFolder().getChildFile (juce::String (productName) + ".lnk"),
                        "LOST DUCK Anti Feedback");
        createShortcut (uninstaller, startMenuFolder().getChildFile ("Uninstall " + juce::String (productName) + ".lnk"),
                        "Remove LOST DUCK Anti Feedback");
        installed.add ("Start menu shortcuts");
    }

    if (wantDesktop && standaloneExe.existsAsFile())
    {
        createShortcut (standaloneExe,
                        sharedDesktopFolder()
                            .getChildFile (juce::String (productName) + ".lnk"),
                        "LOST DUCK Anti Feedback");
        installed.add ("Desktop shortcut");
    }

    registerWithWindows (uninstaller, iconFile, totalBytes);
    installed.add ("Listed in Add or remove programs");

    return makeObject ({ { "ok", true },
                         { "where", wantVst3 ? bundle.getFullPathName() : docsFolder().getFullPathName() },
                         { "installed", installed.joinIntoString ("\n") } });
}

/** Undo. Deliberately leaves the user's settings file alone: an uninstall is not a
    request to lose an activation key, and reinstalling should not mean typing it in
    again. */
juce::var performUninstall()
{
    juce::StringArray removed;

    // Both the default location and wherever an earlier install may have put it. The
    // bundle name is ours, so this cannot delete somebody else's plug-in.
    for (const auto& folder : { vst3Folder(),
                                juce::File ("C:\\Program Files\\Common Files\\VST3") })
    {
        const auto bundle = folder.getChildFile (juce::String (productName) + ".vst3");

        if (bundle.isDirectory() && bundle.deleteRecursively())
            removed.add (bundle.getFullPathName());
    }

    for (const auto* old : supersededBundles)
    {
        const auto stale = vst3Folder().getChildFile (old);

        if (stale.exists())
            stale.deleteRecursively();
    }

    startMenuFolder().deleteRecursively();
    sharedDesktopFolder()
        .getChildFile (juce::String (productName) + ".lnk").deleteFile();

    const auto standalone = docsFolder().getChildFile (juce::String (productName) + ".exe");

    if (standalone.deleteFile())
        removed.add (standalone.getFullPathName());

    for (const auto* doc : { "MANUAL.md", "THIRD-PARTY.txt", "LICENCE.txt", "icon-lostduck-multi.ico" })
        docsFolder().getChildFile (doc).deleteFile();

    unregisterFromWindows();

    // The running uninstaller cannot delete itself, so Windows is asked to do it on the
    // next boot. Leaving a stray exe behind is the alternative.
    const auto self = juce::File::getSpecialLocation (juce::File::currentExecutableFile);
    MoveFileExW (self.getFullPathName().toWideCharPointer(), nullptr, MOVEFILE_DELAY_UNTIL_REBOOT);

    return makeObject ({ { "ok", true },
                         { "removed", removed.joinIntoString ("\n") } });
}

