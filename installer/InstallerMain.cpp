/** The logo, borderless and centred, while WebView2 gets itself started behind it.
    Doubles as the loading screen: the first WebView in a process takes a noticeable
    moment, and staring at nothing is worse than staring at a logo. */
class SplashWindow final : public juce::Component
{
public:
    SplashWindow()
    {
        int size = 0;
        const auto* const data = InstallerUiData::getNamedResource ("logolostduck_png", size);

        if (data != nullptr)
            logo = juce::ImageFileFormat::loadFrom (data, static_cast<size_t> (size));

        setOpaque (true);
        setSize (520, 320);
    }

    /** Centres on the primary display and puts itself on screen. Done by hand because
        this is a bare Component on the desktop rather than a TopLevelWindow -- a
        DocumentWindow would come with a frame, and a splash with a title bar is not a
        splash. */
    void show()
    {
        const auto* const display = juce::Desktop::getInstance().getDisplays().getPrimaryDisplay();
        const auto area = display != nullptr ? display->userArea
                                             : juce::Rectangle<int> (0, 0, 1600, 900);

        setCentrePosition (area.getCentreX(), area.getCentreY());
        addToDesktop (juce::ComponentPeer::windowIsTemporary);
        setAlwaysOnTop (true);
        setVisible (true);
    }

    void paint (juce::Graphics& g) override
    {
        g.fillAll (juce::Colour (0xff0a0f14));

        g.setColour (juce::Colour (0x22ffffff));
        g.drawRect (getLocalBounds(), 1);

        if (logo.isValid())
        {
            const auto area = getLocalBounds().reduced (54, 46).toFloat();
            g.drawImage (logo, area, juce::RectanglePlacement::centred, false);
        }
    }

private:
    juce::Image logo;
};

